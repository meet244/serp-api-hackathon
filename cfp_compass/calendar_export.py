"""Build an .ics file with one all-day event per CFP deadline.

Each event has two reminders (7 days and 1 day before) and a UID derived from the
conference's de-duplication key, so importing the file twice does not duplicate events.
"""

from __future__ import annotations

import hashlib
from datetime import datetime, timedelta, timezone

from icalendar import Alarm, Calendar, Event

from .models import RankedCFP
from .scoring import TRAVEL_LABELS, format_inr

PRODID = "-//CFP Compass//cfp-compass//EN"
REMINDER_DAYS = (7, 1)


def event_uid(key: str) -> str:
    return f"{hashlib.sha256(key.encode('utf-8')).hexdigest()[:32]}@cfp-compass"


def _description(row: RankedCFP) -> str:
    cfp = row.cfp
    lines = [
        f"Submit: {cfp.cfp_url or cfp.source_url}",
        f"Net cost: {format_inr(row.net_cost_inr) if row.net_cost_inr is not None else 'unavailable'}",
        f"Speaker travel support: {TRAVEL_LABELS.get(row.travel.status, row.travel.status)}",
    ]
    if cfp.deadline_is_aoe:
        lines.append("Deadline is AoE (Anywhere on Earth).")
    if cfp.event_start:
        where = "Online" if cfp.is_online else ", ".join(p for p in (cfp.city, cfp.country) if p)
        lines.append(f"Event: {cfp.event_start.isoformat()} to {(cfp.event_end or cfp.event_start).isoformat()}, {where}")
    lines.append("Generated by CFP Compass")
    return "\n".join(lines)


def build_ics(rows: list[RankedCFP], *, generated_at: datetime | None = None) -> bytes:
    stamp = (generated_at or datetime.now(timezone.utc)).astimezone(timezone.utc)
    cal = Calendar()
    cal.add("prodid", PRODID)
    cal.add("version", "2.0")
    cal.add("calscale", "GREGORIAN")
    cal.add("method", "PUBLISH")
    cal.add("x-wr-calname", "CFP deadlines (CFP Compass)")

    for row in rows:
        deadline = row.cfp.cfp_deadline
        if deadline is None:
            continue
        event = Event()
        event.add("uid", event_uid(row.key))
        event.add("dtstamp", stamp)
        event.add("summary", f"CFP closes: {row.cfp.conference_name}")
        event.add("dtstart", deadline)  # a date, so an all-day event (VALUE=DATE)
        event.add("dtend", deadline + timedelta(days=1))
        event.add("description", _description(row))
        url = row.cfp.cfp_url or row.cfp.source_url
        if url:
            event.add("url", url)
        event.add("transp", "TRANSPARENT")
        for days in REMINDER_DAYS:
            alarm = Alarm()
            alarm.add("action", "DISPLAY")
            alarm.add("description", f"CFP for {row.cfp.conference_name} closes in {days} day{'s' if days > 1 else ''}")
            alarm.add("trigger", timedelta(days=-days))
            event.add_component(alarm)
        cal.add_component(event)
    return cal.to_ical()
